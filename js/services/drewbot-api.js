/**
 * Andrew G. Palaran — DrewBot AI Client Service
 * Orchestrates calls to Gemini 1.5 Flash, OpenAI GPT-4o Mini, serverless cloud LLM, and offline knowledge fallback.
 */

window.PortfolioApp = window.PortfolioApp || {};
window.PortfolioApp.services = window.PortfolioApp.services || {};

(function(services, config, storage) {
  'use strict';

  async function callGemini(key, query, history) {
    const geminiUrl = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${encodeURIComponent(key)}`;
    const contents = [];

    (history || []).slice(-4).forEach(h => {
      contents.push({
        role: h.role === 'user' ? 'user' : 'model',
        parts: [{ text: h.content }]
      });
    });

    contents.push({
      role: 'user',
      parts: [{ text: query }]
    });

    const resp = await fetch(geminiUrl, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        systemInstruction: {
          parts: [{ text: config.DREWBOT_SYSTEM_PROMPT }]
        },
        contents,
        generationConfig: {
          temperature: 0.7,
          maxOutputTokens: 500
        }
      })
    });

    if (!resp.ok) {
      const errData = await resp.json().catch(() => ({}));
      throw new Error(errData?.error?.message || `Gemini API returned status ${resp.status}`);
    }

    const data = await resp.json();
    const text = data?.candidates?.[0]?.content?.parts?.[0]?.text;
    if (!text) throw new Error('No response generated by Gemini');
    return text;
  }

  async function callOpenAI(key, query, history) {
    const messages = [
      { role: 'system', content: config.DREWBOT_SYSTEM_PROMPT },
      ...(history || []).slice(-6),
      { role: 'user', content: query }
    ];

    const resp = await fetch('https://api.openai.com/v1/chat/completions', {
      method: 'POST',
      headers: {
        'Content-Type': 'application/json',
        'Authorization': `Bearer ${key}`
      },
      body: JSON.stringify({
        model: 'gpt-4o-mini',
        messages,
        temperature: 0.7,
        max_tokens: 500
      })
    });

    if (!resp.ok) {
      const errData = await resp.json().catch(() => ({}));
      throw new Error(errData?.error?.message || `OpenAI returned status ${resp.status}`);
    }

    const data = await resp.json();
    const text = data?.choices?.[0]?.message?.content;
    if (!text) throw new Error('No content returned by OpenAI');
    return text;
  }

  async function callServerless(query, history) {
    const messages = [
      { role: 'system', content: config.DREWBOT_SYSTEM_PROMPT },
      ...(history || []).slice(-6),
      { role: 'user', content: query }
    ];

    try {
      const resp = await fetch('https://text.pollinations.ai/', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          messages,
          model: 'openai',
          seed: 42
        })
      });

      if (resp.ok) {
        const text = await resp.text();
        if (text && text.trim().length > 0) return text;
      }
    } catch (e) {
      // Fall through to GET endpoint
    }

    const getUrl = `https://text.pollinations.ai/${encodeURIComponent(query)}?system=${encodeURIComponent(config.DREWBOT_SYSTEM_PROMPT)}`;
    const getResp = await fetch(getUrl);
    if (getResp.ok) {
      const text = await getResp.text();
      if (text && text.trim().length > 0) return text;
    }

    throw new Error('Serverless AI endpoint currently unreachable');
  }

  services.drewbotAPI = {
    requestAnswer: async function(query, history) {
      const settings = storage.getAISettings();
      const provider = settings.provider || 'gemini';
      const key = (settings.apiKey || '').trim();

      // 1. Google Gemini API
      if (provider === 'gemini' && key) {
        return await callGemini(key, query, history);
      }

      // 2. OpenAI API
      if (provider === 'openai' && key) {
        return await callOpenAI(key, query, history);
      }

      // 3. Serverless free cloud LLM with automatic fallback
      try {
        return await callServerless(query, history);
      } catch (err) {
        console.warn('Online AI failed, switching to local knowledge fallback:', err);
        return config.getDrewBotFallbackAnswer(query);
      }
    },

    testConnection: async function(provider, key) {
      if (provider === 'gemini') {
        if (!key) throw new Error('Please enter a Google Gemini API key');
        const url = `https://generativelanguage.googleapis.com/v1beta/models/gemini-1.5-flash:generateContent?key=${encodeURIComponent(key)}`;
        const res = await fetch(url, {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            contents: [{ role: 'user', parts: [{ text: 'Hello, respond with one word: Connected' }] }]
          })
        });
        if (!res.ok) {
          const errData = await res.json().catch(() => ({}));
          throw new Error(errData?.error?.message || `Status ${res.status}`);
        }
        return 'Connected to Gemini 1.5 Flash!';
      }

      if (provider === 'openai') {
        if (!key) throw new Error('Please enter an OpenAI API key');
        const res = await fetch('https://api.openai.com/v1/chat/completions', {
          method: 'POST',
          headers: {
            'Content-Type': 'application/json',
            'Authorization': `Bearer ${key}`
          },
          body: JSON.stringify({
            model: 'gpt-4o-mini',
            messages: [{ role: 'user', content: 'Say connected' }],
            max_tokens: 5
          })
        });
        if (!res.ok) {
          const errData = await res.json().catch(() => ({}));
          throw new Error(errData?.error?.message || `Status ${res.status}`);
        }
        return 'Connected to OpenAI GPT-4o Mini!';
      }

      return 'Using Instant Free Cloud AI (No key needed). Ready!';
    }
  };
})(window.PortfolioApp.services, window.PortfolioApp.config, window.PortfolioApp.services.storage);
